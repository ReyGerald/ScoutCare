// Helper functions for directory lookups & filters
const VisayasDirectory = {
  getAllDestinations() {
    return VISAYAS_DESTINATIONS;
  },

  getAllCandidateVenues() {
    return JAMBOREE_CANDIDATE_VENUES;
  },

  getDestinationById(id) {
    return VISAYAS_DESTINATIONS.find(d => d.id === id) || null;
  },

  filterDestinations(province = "all", type = "all", searchQuery = "") {
    return VISAYAS_DESTINATIONS.filter(item => {
      const matchProv = province === "all" || item.province.toLowerCase() === province.toLowerCase();
      const matchType = type === "all" || item.type.toLowerCase() === type.toLowerCase();
      const q = searchQuery.trim().toLowerCase();
      const matchQuery = !q || 
        item.name.toLowerCase().includes(q) || 
        item.municipality.toLowerCase().includes(q) || 
        item.province.toLowerCase().includes(q) ||
        item.activities.some(a => a.toLowerCase().includes(q));
      return matchProv && matchType && matchQuery;
    });
  },

  getProvinces() {
    return ["Cebu", "Bohol", "Antique", "Negros Oriental", "Siquijor", "Samar"];
  },

  getCategories() {
    return ["Scout Camp", "Mountain", "Beach", "River", "Forest", "Waterfall", "Island"];
  }
};

window.VISAYAS_DESTINATIONS = VISAYAS_DESTINATIONS;
window.JAMBOREE_CANDIDATE_VENUES = JAMBOREE_CANDIDATE_VENUES;
window.VisayasDirectory = VisayasDirectory;
